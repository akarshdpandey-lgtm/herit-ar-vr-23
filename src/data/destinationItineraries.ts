export function findCuratedItinerary(locationName: string): CuratedDestinationItinerary | null {
  if (!locationName) return null;
  const clean = locationName.toLowerCase().trim();

  for (const item of CURATED_ITINERARIES) {
    if (item.matches.some(m => clean.includes(m))) {
      return item;
    }
  }
  return null;
}
